#!/usr/bin/env python3
"""Safely mirror the verified PDKS release ZIP into a local creative/PDKS checkout.

Default: dry run. --apply writes files. --push commits and pushes after --apply.
The script never uploads credentials, personal Vault data, .env, node_modules or build output.
"""
from __future__ import annotations
import argparse, hashlib, json, os, shutil, subprocess, sys, tempfile, zipfile
from pathlib import Path, PurePosixPath

EXPECTED_ARCHIVE_SHA256 = "ad44f84d4be5749492c89d2fc3a91a0ae88ba3e75ddda96208cd1e4884b4cbc4"
EXCLUDED_PARTS = {".git", ".venv", "venv", "node_modules", "dist", "build", "__pycache__", ".pytest_cache", "data", "backup", "raw-captures"}
EXCLUDED_NAMES = {".env", ".env.local", ".env.production", "credentials.json", "secrets.json"}

def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()

def safe_member(name: str) -> bool:
    p = PurePosixPath(name)
    return not p.is_absolute() and ".." not in p.parts and not any(x in EXCLUDED_PARTS for x in p.parts) and p.name not in EXCLUDED_NAMES

def run(args, cwd=None):
    return subprocess.run(args, cwd=cwd, check=True, text=True)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--archive", required=True, help="Path to PDKS_0.5.3_完整综合工程包.zip")
    ap.add_argument("--repo", required=True, help="Path to local creative repository checkout")
    ap.add_argument("--apply", action="store_true", help="Copy verified release files into repo/PDKS")
    ap.add_argument("--push", action="store_true", help="After --apply, create a commit and push main")
    ns = ap.parse_args()
    archive, repo = Path(ns.archive).expanduser().resolve(), Path(ns.repo).expanduser().resolve()
    dest = repo / "PDKS"
    if not archive.is_file(): raise SystemExit(f"Archive not found: {archive}")
    if not (repo / ".git").exists(): raise SystemExit(f"Not a Git checkout: {repo}")
    if ns.push and not ns.apply: raise SystemExit("--push requires --apply")
    actual = sha256(archive)
    if actual != EXPECTED_ARCHIVE_SHA256:
        raise SystemExit(f"Archive SHA-256 mismatch: {actual}")
    with tempfile.TemporaryDirectory(prefix="pdks-mirror-") as td:
        temp = Path(td)
        with zipfile.ZipFile(archive) as z:
            bad = z.testzip()
            if bad: raise SystemExit(f"ZIP CRC failure: {bad}")
            members = [n for n in z.namelist() if safe_member(n)]
            if not any(n == "PDKS/MANIFEST.json" for n in members):
                raise SystemExit("Missing PDKS/MANIFEST.json in archive")
            for n in members:
                target = (temp / n).resolve()
                if temp.resolve() not in target.parents and target != temp.resolve():
                    raise SystemExit(f"Unsafe archive path: {n}")
            z.extractall(temp, members=members)
        src = temp / "PDKS"
        manifest_path = src / "MANIFEST.json"
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        errors = []
        for item in manifest.get("files", []):
            rel = PurePosixPath(item["path"])
            if not safe_member(str(rel)): continue
            f = src.joinpath(*rel.parts)
            if not f.is_file(): errors.append(f"missing:{rel}")
            elif f.stat().st_size != item["size_bytes"] or sha256(f) != item["sha256"]:
                errors.append(f"hash:{rel}")
        if errors: raise SystemExit("Manifest validation failed: " + "; ".join(errors[:20]))
        files = [p for p in src.rglob("*") if p.is_file() and safe_member(p.relative_to(src).as_posix())]
        print(f"Verified archive: {len(files)} files; SHA-256 {actual}")
        print(f"Target: {dest}")
        print("Mode:", "APPLY" if ns.apply else "DRY RUN")
        if not ns.apply:
            print("No files changed. Re-run with --apply after reviewing this plan.")
            return
        dest.mkdir(parents=True, exist_ok=True)
        copied = 0
        for f in files:
            rel = f.relative_to(src)
            target = dest / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, target)
            copied += 1
        mirror = {
            "source_archive": archive.name,
            "source_archive_sha256": actual,
            "files_copied": copied,
            "development_stage": "transitional_skill_development",
            "maturity": "experimental_preview",
            "note": "Generated by tools/sync-release.py; excluded credentials, personal runtime data and build caches."
        }
        (dest / "GITHUB_MIRROR_MANIFEST.json").write_text(json.dumps(mirror, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        run(["git", "add", "PDKS"], cwd=repo)
        run(["git", "status", "--short"], cwd=repo)
        if ns.push:
            run(["git", "commit", "-m", "Mirror complete PDKS 0.5.3 preview release"], cwd=repo)
            run(["git", "push", "origin", "main"], cwd=repo)
            print("Pushed to origin/main.")
        else:
            print("Files staged locally. Review git diff --cached; commit/push manually or rerun with --push.")

if __name__ == "__main__":
    main()
